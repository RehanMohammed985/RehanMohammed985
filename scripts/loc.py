"""Count lines of code pushed by USER across their own repos and render header.svg."""
import json, os, sys, time, urllib.request

USER = os.environ.get("GH_USER", "RehanMohammed985")
TOKEN = os.environ.get("GH_TOKEN", "")
OUT = sys.argv[1] if len(sys.argv) > 1 else "header.svg"


def api(path):
    req = urllib.request.Request("https://api.github.com" + path, headers={
        "Accept": "application/vnd.github+json",
        **({"Authorization": f"Bearer {TOKEN}"} if TOKEN else {}),
    })
    with urllib.request.urlopen(req) as r:
        return r.status, (json.loads(r.read() or b"null"))


def repos():
    # /user/repos includes private repos when the token can see them; fall back to public list.
    path = "/user/repos?affiliation=owner&per_page=100&page={}" if TOKEN else f"/users/{USER}/repos?per_page=100&page={{}}"
    page, out = 1, []
    while True:
        try:
            _, batch = api(path.format(page))
        except urllib.error.HTTPError:
            if path.startswith("/user/"):
                path = f"/users/{USER}/repos?per_page=100&page={{}}"
                continue
            raise
        if not batch:
            return out
        out += [r["full_name"] for r in batch if not r["fork"] and r["owner"]["login"] == USER]
        page += 1


def additions(full_name):
    for _ in range(8):  # GitHub returns 202 while it computes stats
        status, data = api(f"/repos/{full_name}/stats/contributors")
        if status == 200 and isinstance(data, list):
            return sum(w["a"] for c in data if c["author"] and c["author"]["login"] == USER for w in c["weeks"])
        time.sleep(3)
    return 0


def svg(total):
    digits = f"{total:,}"
    D, H, W = 10, 44, 26  # loop seconds, digit height, digit width
    x0, y0 = 476, 84
    cols, x = [], x0
    for i, ch in enumerate(digits):
        if ch == ",":
            cols.append(f'<text x="{x - 4}" y="{y0 + 34}" fill="#3fb950" font-size="38">,</text>')
            x += 16
            continue
        v = int(ch)
        stack = "".join(f'<text x="{x}" y="{y0 + 34 + k * H}" fill="#3fb950" font-size="38" font-weight="bold">{k % 10}</text>' for k in range(10 + v + 1))
        end = -(10 + v) * H  # spin once through 0-9, then land on the digit
        start = 0.02 + i * 0.012
        cols.append(
            f'<g clip-path="url(#win)"><g>{stack}'
            f'<animateTransform attributeName="transform" type="translate" dur="{D}s" repeatCount="indefinite" '
            f'values="0 0;0 0;0 {end};0 {end};0 0" keyTimes="0;{start:.3f};{start + 0.28:.3f};0.97;1" '
            f'calcMode="spline" keySplines="0 0 1 1;0.2 0.7 0.2 1;0 0 1 1;0 0 1 1"/></g></g>')
        x += W
    return f'''<svg viewBox="0 0 840 220" xmlns="http://www.w3.org/2000/svg" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace">
  <!-- Generated by scripts/loc.py: lines of code pushed across {USER}'s repos. Rerun the script to refresh. -->
  <defs><clipPath id="win"><rect x="470" y="{y0}" width="350" height="{H}"/></clipPath></defs>
  <rect width="840" height="220" rx="12" fill="#0d1117"/>
  <rect x="0.5" y="0.5" width="839" height="219" rx="12" fill="none" stroke="#30363d"/>
  <text x="40" y="92" fill="#e6edf3" font-size="30" font-weight="bold">Rehan Mohammed</text>
  <text x="40" y="126" fill="#c9d1d9" font-size="17">I build solutions that scale.</text>
  <text x="40" y="154" fill="#8b949e" font-size="13">prev. research @ Cohere · AI eval @ Boardy</text>
  <line x1="446" y1="50" x2="446" y2="170" stroke="#21262d"/>
  <text x="476" y="70" fill="#6e7681" font-size="12">LINES OF CODE PUSHED</text>
  {"".join(cols)}
  <text x="476" y="154" fill="#6e7681" font-size="12">across {len(REPOS)} repos</text>
  <circle cx="800" cy="66" r="4" fill="#3fb950"><animate attributeName="opacity" dur="1.6s" repeatCount="indefinite" values="1;0.2;1"/></circle>
</svg>
'''


REPOS = repos()
total = sum(additions(r) for r in REPOS)
print(f"{total:,} lines across {len(REPOS)} repos", file=sys.stderr)
if total:
    open(OUT, "w").write(svg(total))
